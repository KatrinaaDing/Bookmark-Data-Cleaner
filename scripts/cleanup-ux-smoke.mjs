import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { launch, pause } from './browser-harness.mjs';

const before = process.argv.includes('--capture-before');
const browser = await launch({ grantTestPermissions: true });
try {
  const page = await browser.attach(`chrome-extension://${browser.id}/app.html#bookmarks`);
  const run = expression => browser.evaluate(page.sessionId, expression);
  const waitFor = async expression => {
    for (let i = 0; i < 100; i++) { if (await run(expression)) return; await pause(40); }
    assert.fail(`Timed out: ${expression}`);
  };
  const click = label => run(`Array.from(document.querySelectorAll('.cleanup-dialog button')).find(b => b.textContent === ${JSON.stringify(label)}).click()`);
  const fixture = await run(`(async () => {
    const folder = await chrome.bookmarks.create({title:'UX sample library'});
    const saved = [];
    for (const [title, url] of [['Selected A','https://a.test/page'],['Selected B','https://b.test/page'],['Inspected C','https://shared.test/article']])
      saved.push(await chrome.bookmarks.create({parentId:folder.id,title,url}));
    const copy = await chrome.bookmarks.create({parentId:folder.id,title:'Exact URL copy of C',url:saved[2].url});
    for (let i=1; i<=12; i++) await chrome.bookmarks.create({parentId:folder.id,title:'Saved reference '+i,url:'https://shared.test/page/'+i});
    for (const host of ['a.test','b.test','shared.test']) await chrome.cookies.set({url:'https://'+host+'/',name:'session',value:'synthetic'});
    return {a:saved[0].id,b:saved[1].id,c:saved[2].id,copy:copy.id};
  })()`);
  await browser.cmd('Page.reload', {}, page.sessionId);
  await waitFor(`!!document.querySelector('[data-focus-key="bookmark:${fixture.c}"]')`);
  await run(`document.querySelectorAll('.folder-toggle[aria-expanded="false"]').forEach(b=>b.click())`);
  await run(`document.querySelector('input[aria-label="Select Selected A"]').click(); document.querySelector('input[aria-label="Select Selected B"]').click(); document.querySelector('[data-focus-key="bookmark:${fixture.c}"]').click()`);
  await waitFor(`document.querySelector('.details h2')?.textContent === 'Inspected C'`);
  const out = `dist/cleanup-ux/${before ? 'before' : 'after'}`;
  await mkdir(out, {recursive:true});
  async function capture(name, width=1360, height=900) {
    await browser.cmd('Emulation.setDeviceMetricsOverride',{width,height,deviceScaleFactor:1,mobile:false},page.sessionId);
    await pause(300);
    if (!before && await run(`!!document.querySelector('.cleanup-dialog')`)) {
      assert.equal(await run(`Array.from(document.querySelectorAll('.cleanup-footer button')).every(button=>{const r=button.getBoundingClientRect();return r.width>0 && r.top>=0 && r.bottom<=innerHeight})`),true,'Review actions stay visible without scrolling the content');
      assert.equal(await run(`document.querySelector('.cleanup-dialog').scrollHeight<=document.querySelector('.cleanup-dialog').clientHeight`),true,'Only the review body scrolls');
    }
    const shot = await browser.cmd('Page.captureScreenshot',{format:'png'},page.sessionId);
    await writeFile(`${out}/${name}.png`,Buffer.from(shot.data,'base64'));
  }
  await capture('bookmark-details');
  await capture('bookmark-details-narrow',390,844);
  await run(`document.querySelector('.detail-cleanup').click()`);
  await waitFor(`document.querySelector('.cleanup-dialog') && !document.querySelector('.cleanup-count').textContent.includes('Checking')`);
  await capture('choices');
  if (!before) await capture('choices-narrow',390,844);
  await click('Next');
  await waitFor(`document.querySelector('#cleanup-title')?.textContent.includes('Step 2') && document.querySelector('.cleanup-dialog').getAttribute('aria-busy')==='false'`);
  await capture('review');
  if (!before) await capture('review-narrow',390,844);
  if (before) console.log('Before screenshots captured with synthetic A/B selection and C inspection.');
  else {
    const selectedIds = `Array.from(document.querySelectorAll('.bookmark-row input:checked')).map(input=>input.closest('.bookmark-row').querySelector('[data-focus-key]').dataset.focusKey)`;
    const expectedSelection = [`bookmark:${fixture.a}`, `bookmark:${fixture.b}`];
    assert.deepEqual(await run(selectedIds), expectedSelection);
    assert.match(await run(`document.querySelector('.cleanup-entry').textContent`), /This bookmark: Inspected C.*https:\/\/shared.test\/article/);
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.selected-bookmark .affected-title')).map(el=>el.textContent)`), ['Inspected C']);
    assert.equal(await run(`document.querySelector('.duplicate-choices input').dataset.bookmarkId`), fixture.copy);
    assert.equal(await run(`document.querySelector('.selected-bookmark .bookmark-address-text').textContent`),'https://shared.test/article','Review identifies the full saved URL');
    assert.equal(await run(`document.querySelector('.cleanup-footer').textContent.includes('Deletion cannot be undone.')`),true);
    assert.match(await run(`document.querySelector('.scope-additions').textContent`), /1 additional bookmark/);
    assert.equal(await run(`document.querySelector('.related-warning details').open`), false);
    assert.equal(await run(`document.querySelectorAll('.related-warning .affected-entry').length`), 12);
    assert.match(await run(`document.querySelector('.related-warning').textContent`), /12 saved pages may be affected/);
    assert.equal(await run(`document.activeElement.id`), 'cleanup-title');
    await run(`document.querySelector('.technical-details').open=true;const choice=document.querySelector('.duplicate-choices input');choice.focus();window.reviewScroll=document.querySelector('.cleanup-body').scrollTop;choice.click()`);
    await waitFor(`document.querySelector('.cleanup-dialog').getAttribute('aria-busy')==='false'`);
    assert.equal(await run(`document.querySelector('.technical-details').open`),true,'Scope rebuild preserves disclosure context');
    assert.equal(await run(`Math.abs(document.querySelector('.cleanup-body').scrollTop-window.reviewScroll)<2`),true,'Scope rebuild preserves reading position');
    assert.equal(await run(`document.activeElement.dataset.bookmarkId`),fixture.copy,'Scope rebuild restores the duplicate checkbox focus');
    await run(`document.querySelector('.duplicate-choices input').click()`);
    await waitFor(`document.querySelector('.cleanup-dialog').getAttribute('aria-busy')==='false'`);
    await click('Cancel');
    await waitFor(`!document.querySelector('.cleanup-dialog')`);
    assert.deepEqual(await run(selectedIds), expectedSelection, 'Cancelling C preserves A/B');
    assert.equal(await run(`document.querySelector('.details-drawer').dataset.inspectionKey`), `bookmark:${fixture.c}`);
    await run(`document.querySelector('.details .related-disclosure summary').focus()`);
    assert.equal(await run(`document.activeElement.matches('.related-disclosure summary')`),true);
    await browser.cmd('Input.dispatchKeyEvent',{type:'keyDown',key:'Enter',code:'Enter',windowsVirtualKeyCode:13,text:'\r'},page.sessionId);
    await browser.cmd('Input.dispatchKeyEvent',{type:'keyUp',key:'Enter',code:'Enter',windowsVirtualKeyCode:13},page.sessionId);
    assert.equal(await run(`document.querySelector('.details .related-disclosure').open`),true,'Native disclosure opens from keyboard');
    assert.equal(await run(`document.querySelectorAll('.details .related-disclosure li').length`),13,'All related pages and exact copies remain available');
    await run(`document.querySelector('.details .related-disclosure summary').click()`);
    await waitFor(`!document.querySelector('.details .related-disclosure').open`);
    await capture('bookmark-details-narrow',390,844);
    assert.equal(await run(`document.querySelector('.details-drawer').matches(':modal')`),true);
    assert.equal(await run(`document.querySelector('.details-drawer').scrollWidth <= document.querySelector('.details-drawer').clientWidth`),true);
    await capture('bookmark-details',1360,900);
    assert.equal(await run(`document.querySelector('.detail-cleanup').getBoundingClientRect().bottom < innerHeight`),true,'Cleanup is visible before long supporting lists');
    const filter = `document.querySelector('input[aria-label="Find a bookmark"]')`;
    await run(`${filter}.value='Selected A'; ${filter}.dispatchEvent(new Event('input'))`);
    assert.match(await run(`document.querySelector('section:not([hidden]) .selection-count').textContent`),/2 selected · 1 outside results/);
    await run(`document.querySelector('section:not([hidden]) .toolbar-actions .primary').click()`);
    await waitFor(`document.querySelector('.cleanup-entry')?.textContent === 'Selected: 2 bookmarks'`);
    await click('Next');
    await waitFor(`document.querySelector('#cleanup-title')?.textContent.includes('Step 2')`);
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.selected-bookmark .affected-title')).map(el=>el.textContent).sort()`),['Selected A','Selected B'],'Hidden selections remain in bulk scope');
    await click('Cancel');
    await run(`document.querySelector('[data-focus-key="bookmark:${fixture.a}"]').click()`);
    await waitFor(`document.querySelector('.details h2')?.textContent==='Selected A'`);
    await run(`${filter}.value=''; ${filter}.dispatchEvent(new Event('input'))`);
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('[data-focus-key][aria-current="true"]')).map(node=>node.dataset.focusKey)`),[`bookmark:${fixture.a}`],'Restoring the cached tree marks the current inspection, not its former row');
    await run(`document.querySelector('[data-focus-key="bookmark:${fixture.c}"]').click()`);
    await waitFor(`document.querySelector('.details h2')?.textContent==='Inspected C'`);
    await run(`document.querySelector('input[aria-label="Select Selected A"]').click()`);
    assert.equal(await run(`document.querySelector('.details h2').textContent`),'Inspected C','Checkbox does not switch details');
    await run(`document.querySelector('input[aria-label="Select Selected A"]').click(); document.querySelector('.detail-cleanup').click()`);
    await waitFor(`!!document.querySelector('.cleanup-dialog')`);
    await run(`document.querySelector('#cleanup-count-bookmarks').closest('.cleanup-choice').querySelector('input').click()`);
    await click('Next');
    await waitFor(`document.querySelector('#cleanup-title')?.textContent.includes('Step 2')`);
    assert.equal(await run(`document.querySelector('.bookmark-removals')===null`),true);
    assert.match(await run(`document.querySelector('.cleanup-dialog').textContent`),/No bookmarks will be deleted/);
    assert.equal(await run(`document.querySelectorAll('.related-warning .affected-entry').length`),14,'Data-only review includes C, its copy and all related pages');
    await capture('data-only-review');
    await click('Back');
    await run(`document.querySelectorAll('.cleanup-choice input').forEach(input=>{const wanted=input.closest('.cleanup-choice').querySelector('#cleanup-count-bookmarks')!==null; if(input.checked!==wanted) input.click()})`);
    await click('Next');
    await waitFor(`!!document.querySelector('.duplicate-choices input')`);
    await run(`document.querySelector('.duplicate-choices input').click()`);
    await waitFor(`document.querySelector('.cleanup-dialog').getAttribute('aria-busy')==='false'`);
    await click('Back'); await click('Next');
    await waitFor(`!!document.querySelector('.duplicate-choices input')`);
    assert.equal(await run(`document.querySelector('.duplicate-choices input').checked`),false,'Back/Next preserves explicit duplicate deselection');
    assert.equal(await run(`document.querySelector('.related-warning')===null`),true,'Bookmark-only removal has no shared-data effects');
    await click('Confirm cleanup');
    await waitFor(`!document.querySelector('.cleanup-dialog')`);
    await waitFor(`!document.querySelector('[data-focus-key="bookmark:${fixture.c}"]')`);
    assert.deepEqual(await run(selectedIds),expectedSelection,'Actual cleanup reconciles without clearing unrelated selection');
    assert.match(await run(`document.querySelector('.details-drawer').textContent`),/no longer available/);
    assert.equal(await run(`chrome.bookmarks.get(${JSON.stringify(fixture.copy)}).then(()=>true,()=>false)`),true,'Explicitly deselected copy really survives');
    await run(`location.hash='sites'`);
    await waitFor(`!!document.querySelector('[data-focus-key="site:shared.test"]')`);
    await run(`document.querySelector('input[aria-label="Select a.test"]').click();document.querySelector('input[aria-label="Select b.test"]').click();document.querySelector('[data-focus-key="site:shared.test"]').click()`);
    await waitFor(`document.querySelector('.details h2')?.textContent==='shared.test'`);
    assert.equal(await run(`document.querySelector('.saved-pages-disclosure').open`),false);
    assert.equal(await run(`document.querySelectorAll('.saved-page').length`),13);
    await capture('site-details');
    await capture('site-details-narrow',390,844);
    await run(`document.querySelector('.saved-pages-disclosure').open=true;document.querySelector('.saved-page .bookmark-edit-action').click()`);
    await waitFor(`!!document.querySelector('.bookmark-editor')`);
    assert.equal(await run(`document.activeElement.closest('.bookmark-editor')!==null`),true,'Expanded saved pages retain editing and focus');
    await run(`document.querySelector('.bookmark-editor .negative').click()`);
    await waitFor(`!document.querySelector('.bookmark-editor')`);
    await run(`document.querySelector('.detail-cleanup').click()`);
    await waitFor(`document.querySelector('.cleanup-entry')?.textContent==='This site: shared.test'`);
    await click('Next');
    await waitFor(`document.querySelector('#cleanup-title')?.textContent.includes('Step 2')`);
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.cleanup-targets .affected-title')).map(el=>el.textContent)`),['shared.test']);
    assert.equal(await run(`document.querySelector('.bookmark-removals')===null`),true,'Site cleanup keeps bookmark deletion unavailable');
    await click('Cancel');
    assert.equal(await run(`document.querySelectorAll('.site-row input:checked').length`),2);
    await capture('site-details-expanded',1360,900);
    await run(`document.querySelector('section:not([hidden]) .toolbar-actions .primary').click()`);
    await waitFor(`document.querySelector('.cleanup-entry')?.textContent==='Selected: 2 sites'`);
    await click('Next');
    await waitFor(`document.querySelector('#cleanup-title')?.textContent.includes('Step 2')`);
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.cleanup-targets .affected-title')).map(el=>el.textContent).sort()`),['a.test','b.test']);
    await click('Cancel');
    const reports = await run(`(async()=>{
      const {operationStatus}=await import('./components/operation-status.js');
      return ['failed','unverified'].map(status=>operationStatus({id:status,status:status==='unverified'?'unverified':'finished',completed:1,total:1,outcomes:[{target:'synthetic.test',kind:'data',status,message:'Synthetic incomplete outcome'}]}).textContent);
    })()`);
    assert.match(reports[0],/items to review.*1 operation failed/);
    assert.match(reports[1],/interrupted.*1 outcome unverified/);
    assert.equal(reports.some(report=>report.includes('Selected cleanup requests completed')),false,'Failed and unverified results are never labelled successful');
    console.log('Cleanup UX: independent A/B/C scope, cancel, hidden selections, retained effects, disclosure keyboard/editing, desktop/narrow views, duplicate decisions and actual deletion reconciliation passed.');
  }
} finally { await browser.close(); }
